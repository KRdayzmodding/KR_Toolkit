def dark() -> bool:
    """Тёмная ли тема прямо сейчас."""
    return isDarkTheme()


def color(role: str) -> str:
    """Цвет роли под текущую тему. Неизвестная роль — цвет обычного текста,
    чтобы опечатка не превратила строку в невидимую."""
    table = _DARK if isDarkTheme() else _LIGHT
    return table.get(role, table["text"])


def tint(role: str, alpha: float = 0.16) -> str:
    """Цвет роли как полупрозрачная заливка для таблиц стилей.

    Именно rgba(), а не восьмизначный hex: Qt читает #AABBCCDD как
    #AARRGGBB — альфа идёт первой. Дописанная в конец прозрачность
    превращала зелёный в мутно-коричневый.
    """
    value = color(role).lstrip("#")
    r, g, b = (int(value[i:i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r}, {g}, {b}, {alpha})"


def colors(*roles: str) -> dict[str, str]:
    """Несколько ролей разом: colors('error', 'warning') -> {'error': ...}."""
    return {r: color(r) for r in roles}


def level_colors() -> dict[str, str]:
    """Цвета уровней строки журнала — общий словарь для всех логов."""
    return {"error": color("error"), "warning": color("warning"),
            "info": color("console_fg"), "success": color("success"),
            "session": color("info")}


def token_colors() -> dict[str, str]:
    """Подсветка кусков строки лога: время, тег, строка в кавычках, число."""
    return {"time": color("log_time"), "tag": color("log_tag"),
            "string": color("log_string"), "number": color("log_number")}


