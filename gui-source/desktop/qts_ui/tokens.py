# Cascadia Mono — родной моноширинный шрифт Windows 11 и Терминала; Consolas
# остаётся запасным для Windows 10. Кегль 10 вместо прежних 9: на экранах с
# масштабом 150% девятка читается с трудом, а логи читают подолгу.
MONO_FAMILIES = ["Cascadia Mono", "Consolas", "Courier New"]
MONO_PT = 10


def mono_font(pt: int = MONO_PT) -> QFont:
    """Моноширинный шрифт логов и консолей.

    setFamilies, а не имя строкой: Qt берёт первое семейство, которое реально
    установлено, и на Windows 10 без Cascadia молча переходит к Consolas.
    """
    f = QFont()
    f.setFamilies(MONO_FAMILIES)
    f.setPointSize(pt)
    return f


def console_qss() -> str:
    """Оформление текстовых консолей: журнал запуска, логи, вывод pboProject."""
    return (f"QPlainTextEdit{{background:{color('console_bg')};"
            f"color:{color('console_fg')};border:1px solid {color('border')};"
            f"border-radius:{RADIUS_FIELD}px;padding:6px;}}")


def apply_console(view) -> None:
    """Красит консоль и перекрашивает её при каждой смене темы.

    Одного setStyleSheet мало: таблица стилей, выданная при сборке окна,
    остаётся от той темы, что была в тот момент. Человек переключает тему в
    настройках, всё вокруг светлеет, а консоль остаётся чёрной дырой —
    ровно это и было видно. Поэтому подписываемся на themeChanged.

    Отписка по destroyed обязательна: окна логов создаются и закрываются, а
    сигнал, оставшийся висеть на удалённом виджете, уронил бы приложение при
    следующем переключении темы.
    """
    def paint() -> None:
        view.setStyleSheet(console_qss())

    def drop() -> None:
        # При закрытии программы qconfig успевает уйти раньше виджетов, и
        # отписываться становится не от чего — это не ошибка, а порядок
        # разрушения. Без глушения на выходе печатается трассировка.
        try:
            qconfig.themeChanged.disconnect(paint)
        except (RuntimeError, TypeError):
            pass

    paint()
    qconfig.themeChanged.connect(paint)
    view.destroyed.connect(drop)


